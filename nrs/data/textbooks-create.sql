-- Oracle schema for textbooks, units, items, and drills
-- Matches existing style: quoted identifiers, sequences, CLOBs for JSON

CREATE SEQUENCE TEXTBOOK_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE UNIT_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE ITEM_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE DRILL_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE "TEXTBOOK" (
    "TEXTBOOK_ID"   NUMBER PRIMARY KEY,
    "TITLE"         VARCHAR2(200) NOT NULL,
    "LANGUAGE"      VARCHAR2(50) NOT NULL,
    "LEVEL"         VARCHAR2(50),
    "DESCRIPTION"   VARCHAR2(1000),
    "CREATED_BY"    NUMBER,
    "CREATED_AT"    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "UNIT" (
    "UNIT_ID"       NUMBER PRIMARY KEY,
    "TEXTBOOK_ID"   NUMBER REFERENCES "TEXTBOOK"("TEXTBOOK_ID") ON DELETE CASCADE,
    "TITLE"         VARCHAR2(200) NOT NULL,
    "ORDER_INDEX"   NUMBER DEFAULT 0,
    "PARENT_ID"     NUMBER REFERENCES "UNIT"("UNIT_ID")
);

CREATE TABLE "ITEM" (
    "ITEM_ID"       NUMBER PRIMARY KEY,
    "UNIT_ID"       NUMBER REFERENCES "UNIT"("UNIT_ID") ON DELETE SET NULL,
    "TEXTBOOK_ID"   NUMBER REFERENCES "TEXTBOOK"("TEXTBOOK_ID") ON DELETE SET NULL,
    "TYPE"          VARCHAR2(50) DEFAULT 'vocab',
    "LANGUAGE"      VARCHAR2(50) NOT NULL,
    "TERM"          VARCHAR2(500) NOT NULL,
    "TRANSLATION"   VARCHAR2(500),
    "DEFINITION"    VARCHAR2(1000),
    "EXAMPLE"       VARCHAR2(1000),
    "NOTES"         VARCHAR2(1000),
    "DATA"          CLOB,
    "DIFFICULTY"    NUMBER,
    "CREATED_BY"    NUMBER,
    "CREATED_AT"    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "DRILL" (
    "DRILL_ID"      NUMBER PRIMARY KEY,
    "TITLE"         VARCHAR2(200) NOT NULL,
    "DESCRIPTION"   VARCHAR2(1000),
    "TEXTBOOK_ID"   NUMBER REFERENCES "TEXTBOOK"("TEXTBOOK_ID") ON DELETE SET NULL,
    "UNIT_ID"       NUMBER REFERENCES "UNIT"("UNIT_ID") ON DELETE SET NULL,
    "TYPE"          VARCHAR2(50) DEFAULT 'vocab',
    "CONFIG"        CLOB,
    "CREATED_BY"    NUMBER,
    "CREATED_AT"    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "DRILL_ITEM" (
    "DRILL_ID"      NUMBER REFERENCES "DRILL"("DRILL_ID") ON DELETE CASCADE,
    "ITEM_ID"       NUMBER REFERENCES "ITEM"("ITEM_ID") ON DELETE CASCADE,
    "ORDER_INDEX"   NUMBER DEFAULT 0,
    PRIMARY KEY ("DRILL_ID", "ITEM_ID")
);

CREATE TABLE "CLASSROOM_TEXTBOOK" (
    "CLASSROOM_ID"  NUMBER REFERENCES "CLASSROOM"("CLASSROOM_ID") ON DELETE CASCADE,
    "TEXTBOOK_ID"   NUMBER REFERENCES "TEXTBOOK"("TEXTBOOK_ID") ON DELETE CASCADE,
    PRIMARY KEY ("CLASSROOM_ID", "TEXTBOOK_ID")
);

CREATE TABLE "CLASSROOM_DRILL" (
    "CLASSROOM_ID"  NUMBER REFERENCES "CLASSROOM"("CLASSROOM_ID") ON DELETE CASCADE,
    "DRILL_ID"      NUMBER REFERENCES "DRILL"("DRILL_ID") ON DELETE CASCADE,
    PRIMARY KEY ("CLASSROOM_ID", "DRILL_ID")
);

-- Triggers to auto-populate IDs from sequences
CREATE OR REPLACE TRIGGER TEXTBOOK_BI
BEFORE INSERT ON "TEXTBOOK"
FOR EACH ROW
BEGIN
    IF :NEW."TEXTBOOK_ID" IS NULL THEN
        SELECT TEXTBOOK_SEQ.NEXTVAL INTO :NEW."TEXTBOOK_ID" FROM DUAL;
    END IF;
END;
/

CREATE OR REPLACE TRIGGER UNIT_BI
BEFORE INSERT ON "UNIT"
FOR EACH ROW
BEGIN
    IF :NEW."UNIT_ID" IS NULL THEN
        SELECT UNIT_SEQ.NEXTVAL INTO :NEW."UNIT_ID" FROM DUAL;
    END IF;
END;
/

CREATE OR REPLACE TRIGGER ITEM_BI
BEFORE INSERT ON "ITEM"
FOR EACH ROW
BEGIN
    IF :NEW."ITEM_ID" IS NULL THEN
        SELECT ITEM_SEQ.NEXTVAL INTO :NEW."ITEM_ID" FROM DUAL;
    END IF;
END;
/

CREATE OR REPLACE TRIGGER DRILL_BI
BEFORE INSERT ON "DRILL"
FOR EACH ROW
BEGIN
    IF :NEW."DRILL_ID" IS NULL THEN
        SELECT DRILL_SEQ.NEXTVAL INTO :NEW."DRILL_ID" FROM DUAL;
    END IF;
END;
/
