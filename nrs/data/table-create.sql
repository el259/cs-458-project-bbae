ON DELETE CASCADE;

ALTER TABLE "CLASSROOM_ASSIGNMENT"
ADD CONSTRAINT "FK_CLASSROOM_ASSIGNMENT_QUIZ"
FOREIGN KEY ("QUIZ_ID")
REFERENCES "QUIZ" ("QUIZ_ID");

ALTER TABLE "QUIZ"
ADD CONSTRAINT "FK_ASSIGNMENT_CREATOR"
