CREATE TABLE "APP_USER" (
    "USER_ID" INTEGER GENERATED ALWAYS AS IDENTITY NOT NULL,
    "EMAIL" VARCHAR2(255) NOT NULL UNIQUE,
    "FIRST_NAME" VARCHAR2(100) NOT NULL,
    "LAST_NAME" VARCHAR2(100) NOT NULL,
    "PWD_HASH" VARCHAR2(255) NOT NULL,
    "CREATED_AT" TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "IS_ACTIVE" CHAR(1) DEFAULT 'Y' NOT NULL,
    "IS_ADMIN" CHAR(1) DEFAULT 'N' NOT NULL,
    PRIMARY KEY ("USER_ID")
);

CREATE TABLE "CLASSROOM" (
    "CLASSROOM_ID" INTEGER GENERATED ALWAYS AS IDENTITY NOT NULL,
    "CLASSROOM_NAME" VARCHAR2(200) NOT NULL,
    "DESCRIPTION" VARCHAR2(2000),
    "CREATED_AT" TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "IS_ACTIVE" CHAR(1) DEFAULT 'Y' NOT NULL,
    PRIMARY KEY ("CLASSROOM_ID")
);

CREATE TABLE "CLASSROOM_MEMBERSHIP" (
    "MEMBERSHIP_ID" INTEGER GENERATED ALWAYS AS IDENTITY NOT NULL,
    "CLASSROOM_ID" INTEGER NOT NULL,
    "USER_ID" INTEGER NOT NULL,
    "ROLE" VARCHAR2(20) DEFAULT 'student' NOT NULL,
    "JOINED_AT" TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    PRIMARY KEY ("MEMBERSHIP_ID"),
    CONSTRAINT "CLASSROOM_MEMBERSHIP_UNIQUE_0"
        UNIQUE ("CLASSROOM_ID", "USER_ID")
);

CREATE TABLE "CLASSROOM_ASSIGNMENT" (
    "CLASSROOM_ASSIGNMENT_ID" INTEGER GENERATED ALWAYS AS IDENTITY NOT NULL,
    "CLASSROOM_ID" INTEGER NOT NULL,
    "QUIZ_ID" INTEGER NOT NULL,
    "POINTS_POSSIBLE" NUMBER(8,2) DEFAULT 100 NOT NULL,
    "ATTEMPTS_ALLOWED" INTEGER DEFAULT 1 NOT NULL,
    "AVAILABLE_AT" TIMESTAMP,
    "DUE_AT" TIMESTAMP,
    "CREATED_AT" TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    PRIMARY KEY ("CLASSROOM_ASSIGNMENT_ID"),
    CONSTRAINT "CLASSROOM_QUIZ_UNIQUE_0"
        UNIQUE ("CLASSROOM_ID", "QUIZ_ID")
);

CREATE TABLE "QUIZ" (
    "QUIZ_ID" INTEGER GENERATED ALWAYS AS IDENTITY NOT NULL,
    "CREATOR_ID" INTEGER NOT NULL,
    "TITLE" VARCHAR2(200) NOT NULL,
    "DESCRIPTION" VARCHAR2(2000),
    "QUIZ_JSON" CLOB NOT NULL,
    "CREATED_AT" TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    PRIMARY KEY ("QUIZ_ID")
);

CREATE TABLE "QUIZ_ATTEMPT" (
    "ATTEMPT_ID" INTEGER GENERATED ALWAYS AS IDENTITY NOT NULL,
    "CLASSROOM_ASSIGNMENT_ID" INTEGER NOT NULL,
    "USER_ID" INTEGER NOT NULL,
    "ATTEMPT_NUMBER" INTEGER NOT NULL,
    "STARTED_AT" TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    "SUBMITTED_AT" TIMESTAMP,
    "SCORE" NUMBER(8,2),
    "RESPONSE_JSON" CLOB NOT NULL,
    PRIMARY KEY ("ATTEMPT_ID"),
    CONSTRAINT "QUIZ_ATTEMPT_UNIQUE_0"
        UNIQUE (
            "CLASSROOM_ASSIGNMENT_ID",
            "USER_ID",
            "ATTEMPT_NUMBER"
        )
);

